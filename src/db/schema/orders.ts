import { sql } from "drizzle-orm";
import {
  type AnyPgColumn,
  bigint,
  boolean,
  check,
  date,
  index,
  integer,
  jsonb,
  pgTable,
  text,
  timestamp,
  uuid,
} from "drizzle-orm/pg-core";
import { kg, money, percent, pk, restrict, timestamps } from "./_common";
import { boxOwnership, deliveryMethod, orderItemKind, orderStatus, paymentKind } from "./enums";
import { clientAddresses, clients } from "./clients";
import { boxTypes, createdBy, iceTypes, locations, orderSources, profiles } from "./reference";

// Замовлення (розділ 4.3 ТЗ).

export const orders = pgTable(
  "orders",
  {
    id: pk(),
    /**
     * Номер замовлення. `generated by default`: при імпорті (B7) старі номери можна
     * задавати явно, а потім перевести лічильник командою `alter ... restart with`.
     */
    number: integer("number").unique().generatedByDefaultAsIdentity(),
    locationId: uuid("location_id")
      .notNull()
      .references(() => locations.id, restrict),
    clientId: uuid("client_id")
      .notNull()
      .references(() => clients.id, restrict),
    status: orderStatus("status").notNull().default("draft"),
    sourceId: uuid("source_id").references(() => orderSources.id, restrict),
    /** Дата виконання. */
    orderDate: date("order_date").notNull(),
    iceTypeId: uuid("ice_type_id").references(() => iceTypes.id, restrict),
    kgSold: kg("kg_sold").notNull().default("0"),
    kgToProduce: kg("kg_to_produce").notNull().default("0"),
    markupPercentApplied: percent("markup_percent_applied"),
    /** Ціна за кг, зафіксована при підтвердженні: подальші зміни прайсу замовлення не міняють. */
    pricePerKgSnapshot: money("price_per_kg_snapshot"),
    /**
     * Ціну в чернетці вказав менеджер вручну (D52). Без цього ціна береться з картки клієнта чи
     * прайсу й перераховується, поки замовлення не підтверджене.
     */
    priceManual: boolean("price_manual").notNull().default(false),
    deliveryMethod: deliveryMethod("delivery_method").notNull().default("other"),
    addressId: uuid("address_id").references(() => clientAddresses.id, restrict),
    deliveryText: text("delivery_text"),
    timeWindow: text("time_window"),
    recipientName: text("recipient_name"),
    recipientPhone: text("recipient_phone"),
    boxTypeId: uuid("box_type_id").references(() => boxTypes.id, restrict),
    boxCount: integer("box_count").notNull().default(0),
    boxOwnership: boxOwnership("box_ownership").notNull().default("ours"),
    comment: text("comment"),
    internalComment: text("internal_comment"),
    paymentKind: paymentKind("payment_kind").notNull().default("unknown"),
    /** Сума замовлення: перераховується тригером за позиціями. */
    total: money("total").notNull().default("0"),
    confirmedAt: timestamp("confirmed_at", { withTimezone: true }),
    confirmedBy: uuid("confirmed_by").references(() => profiles.id, restrict),
    producedAt: timestamp("produced_at", { withTimezone: true }),
    packedAt: timestamp("packed_at", { withTimezone: true }),
    shippedAt: timestamp("shipped_at", { withTimezone: true }),
    paidAt: timestamp("paid_at", { withTimezone: true }),
    closedAt: timestamp("closed_at", { withTimezone: true }),
    /** Коли виробництво вперше побачило замовлення (для позначки «нове»). */
    seenByProductionAt: timestamp("seen_by_production_at", { withTimezone: true }),
    telegramMessageId: bigint("telegram_message_id", { mode: "number" }),
    telegramChatId: bigint("telegram_chat_id", { mode: "number" }),
    /** Сирий результат розбору заявки (AI). */
    draftPayload: jsonb("draft_payload"),
    duplicateOf: uuid("duplicate_of").references((): AnyPgColumn => orders.id, restrict),
    /** Чому замовлення скасовано (обов'язково для нових скасувань, D51). */
    cancelReason: text("cancel_reason"),
    /** Імпортовані архівні замовлення (B7). */
    isArchive: boolean("is_archive").notNull().default(false),
    deletedAt: timestamp("deleted_at", { withTimezone: true }),
    createdBy: createdBy(),
    ...timestamps,
  },
  (t) => [
    index("orders_location_date_status_idx").on(t.locationId, t.orderDate, t.status),
    index("orders_client_id_idx").on(t.clientId),
    index("orders_status_idx").on(t.status),
    index("orders_source_id_idx").on(t.sourceId),
    index("orders_ice_type_id_idx").on(t.iceTypeId),
    index("orders_address_id_idx").on(t.addressId),
    index("orders_box_type_id_idx").on(t.boxTypeId),
    index("orders_confirmed_by_idx").on(t.confirmedBy),
    index("orders_duplicate_of_idx").on(t.duplicateOf),
    index("orders_created_by_idx").on(t.createdBy),
    // Пошук дублів і «як минулого разу»: замовлення клієнта за датою.
    index("orders_client_date_idx").on(t.clientId, t.orderDate),
    // Підтверджене замовлення вже має зафіксовану ціну (D52). Чернетка й скасоване її не мають;
    // імпортовані архівні замовлення (B7) цього правила не стосується.
    check(
      "orders_confirmed_has_price",
      sql`${t.status} in ('draft', 'cancelled') or ${t.isArchive} or ${t.pricePerKgSnapshot} is not null`,
    ),
    // Нове скасування має причину (D51).
    check(
      "orders_cancelled_has_reason",
      sql`${t.status} <> 'cancelled' or ${t.isArchive} or length(btrim(coalesce(${t.cancelReason}, ''))) > 0`,
    ),
    check("orders_kg_sold_ok", sql`${t.kgSold} >= 0`),
    check("orders_kg_to_produce_ok", sql`${t.kgToProduce} >= 0`),
    check("orders_box_count_ok", sql`${t.boxCount} >= 0`),
    check("orders_total_ok", sql`${t.total} >= 0`),
    check(
      "orders_markup_range",
      sql`${t.markupPercentApplied} is null or (${t.markupPercentApplied} >= 0 and ${t.markupPercentApplied} <= 100)`,
    ),
    check(
      "orders_recipient_phone_e164",
      sql`${t.recipientPhone} is null or ${t.recipientPhone} ~ '^[+][0-9]{8,15}$'`,
    ),
  ],
).enableRLS();

export const orderItems = pgTable(
  "order_items",
  {
    id: pk(),
    orderId: uuid("order_id")
      .notNull()
      .references(() => orders.id, { onDelete: "cascade" }),
    kind: orderItemKind("kind").notNull(),
    title: text("title").notNull(),
    qty: kg("qty").notNull().default("1"),
    /** Одиниця виміру: кг, шт, послуга. */
    unit: text("unit").notNull().default("шт"),
    price: money("price").notNull().default("0"),
    /** Сума позиції: кількість × ціна, округлена до копійки. Рахує база. */
    amount: money("amount")
      .notNull()
      .generatedAlwaysAs(sql`round("qty" * "price", 2)`),
    boxTypeId: uuid("box_type_id").references(() => boxTypes.id, restrict),
    createdBy: createdBy(),
    ...timestamps,
  },
  (t) => [
    index("order_items_order_id_idx").on(t.orderId),
    index("order_items_box_type_id_idx").on(t.boxTypeId),
    index("order_items_created_by_idx").on(t.createdBy),
    check("order_items_values_ok", sql`${t.qty} >= 0 and ${t.price} >= 0`),
  ],
).enableRLS();

/** Історія статусів замовлення. Заповнюється тригером. */
export const orderStatusHistory = pgTable(
  "order_status_history",
  {
    id: pk(),
    orderId: uuid("order_id")
      .notNull()
      .references(() => orders.id, { onDelete: "cascade" }),
    /** Порожній для запису про створення замовлення. */
    fromStatus: orderStatus("from_status"),
    toStatus: orderStatus("to_status").notNull(),
    changedBy: uuid("changed_by").references(() => profiles.id, restrict),
    // clock_timestamp(), а не now(): кілька змін в одній транзакції мають різний час.
    changedAt: timestamp("changed_at", { withTimezone: true })
      .notNull()
      .default(sql`clock_timestamp()`),
    note: text("note"),
  },
  (t) => [
    index("order_status_history_order_id_idx").on(t.orderId, t.changedAt),
    index("order_status_history_changed_by_idx").on(t.changedBy),
  ],
).enableRLS();

/**
 * Зміни ціни підтвердженого замовлення (D52): це може зробити лише власник і лише з приміткою.
 * Кожна зміна лишає тут слід: хто, коли, стара й нова ціна за кг, чому.
 */
export const orderPriceChanges = pgTable(
  "order_price_changes",
  {
    id: pk(),
    orderId: uuid("order_id")
      .notNull()
      .references(() => orders.id, { onDelete: "cascade" }),
    oldPrice: money("old_price").notNull(),
    newPrice: money("new_price").notNull(),
    note: text("note").notNull(),
    changedBy: uuid("changed_by").references(() => profiles.id, restrict),
    changedAt: timestamp("changed_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    index("order_price_changes_order_id_idx").on(t.orderId, t.changedAt),
    index("order_price_changes_changed_by_idx").on(t.changedBy),
    check("order_price_changes_values_ok", sql`${t.oldPrice} >= 0 and ${t.newPrice} >= 0`),
    check("order_price_changes_note_ok", sql`length(btrim(${t.note})) > 0`),
  ],
).enableRLS();
