/** Пункти підказки для того, хто дивиться: ті, що без обмежень, плюс дозволені за правами. */
export function visibleHintItems(
  hint: ScreenHintData,
  access: { work?: boolean; edit?: boolean } = {},
): HintItem[] {
  return hint.items.filter(
    (item) => !item.for || (item.for === "work" ? access.work || access.edit : access.edit),
  );
}
